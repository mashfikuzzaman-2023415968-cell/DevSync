# §9.10 status weights as whole percentages (progress_pct is derived, never typed in, D143).
STATUS_PROGRESS: dict[TaskStatus, int] = {
    TaskStatus.TODO: 0,
    TaskStatus.IN_PROGRESS: 50,
    TaskStatus.REVIEW: 85,
    TaskStatus.DONE: 100,
}

# The §9.1.6 evidence catalogue: the only allowed `activity_events.type` values (a CHECK too).
ACTIVITY_TYPES: tuple[str, ...] = (
    "checkin.posted",
    "checkin.missed",
    "comment.posted",
    "comment.replied",
    "task.moved",
    "task.done",
    "task.reopened",
    "task.evidence_added",
    "milestone.submitted",
    "milestone.approved",
    "milestone.changes_requested",
    "milestone.auto_approved",
    "work.started",
    "blocker.reported",
    "blocker.answered",
    "github.pr_merged",
    "github.review_given",
    "split.proposed",
    "split.agreed",
    "split.objected",
    "member.left",
    "member.replaced",
)

_ACTIVITY_CHECK = "type IN (" + ", ".join(f"'{t}'" for t in ACTIVITY_TYPES) + ")"
_PROGRESS_CHECK = (
    "(status = 'TODO' AND progress_pct = 0) OR (status = 'IN_PROGRESS' AND progress_pct = 50)"
    " OR (status = 'REVIEW' AND progress_pct = 85) OR (status = 'DONE' AND progress_pct = 100)"
)


class Task(UUIDPrimaryKey, Timestamps, Base):
    __tablename__ = "tasks"

    project_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("projects.id", ondelete="CASCADE"), nullable=False
    )
    milestone_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("milestones.id", ondelete="CASCADE"), nullable=False
    )
    title: Mapped[str] = mapped_column(Text, nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False, server_default="")
    assignee_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id"))
    status: Mapped[TaskStatus] = mapped_column(
        _pg_enum(TaskStatus, "task_status"),
        nullable=False,
        server_default=TaskStatus.TODO.value,
    )
    deadline: Mapped[date | None] = mapped_column(Date)
    estimate_hours: Mapped[Decimal] = mapped_column(Numeric(5, 1), nullable=False)
    difficulty: Mapped[TaskDifficulty] = mapped_column(
        _pg_enum(TaskDifficulty, "task_difficulty"), nullable=False
    )
    # Byte order, so the base-62 keys sort as numbers whatever the database locale (D144).
    position: Mapped[str] = mapped_column(Text(collation="C"), nullable=False)
    progress_pct: Mapped[int] = mapped_column(SmallInteger, nullable=False, server_default="0")
    last_activity_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    created_by: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), nullable=False)
    version: Mapped[int] = mapped_column(Integer, nullable=False, server_default="1")

    __table_args__ = (
        CheckConstraint("char_length(title) BETWEEN 1 AND 160", name="title_len"),
        CheckConstraint("char_length(description) <= 5000", name="description_len"),
        CheckConstraint("estimate_hours > 0 AND estimate_hours <= 999.9", name="estimate_range"),
        CheckConstraint("position ~ '^[0-9A-Za-z]{1,64}$'", name="position_format"),
        CheckConstraint(_PROGRESS_CHECK, name="progress_matches_status"),
        CheckConstraint("version >= 1", name="version_positive"),
        Index("ix_tasks_milestone_status_position", "milestone_id", "status", "position"),
        Index("ix_tasks_project_assignee", "project_id", "assignee_id"),
    )


