"""Workspace and monitoring tables (spec §7.5, §7.8; migration 0016; D141–D172).

Every workspace row carries its `project_id` (D166): a guard trigger checks it matches the parent
and keeps it immutable, so the RLS policies are one helper call per row. Reading is for the
project's participants (its client and its ACTIVE or COMPLETED members, D142); writing follows
§2.2 in the services, with RLS as the second gate.

- `tasks` (§8 Task): one-step moves, `progress_pct` derived from the status (§9.10 weights),
  fractional `position` keys generated by the server (D144), `version` for `If-Match` (D172).
- `task_dependencies`: same milestone only, acyclic (the service checks cycles; a trigger checks
  the milestone).
- `task_evidence` (D148, D168): FILE / SCREENSHOT reference a project file, LINK / PR an https URL
  that is never fetched. Append-only.
- `comments` / `discussion_*` (D146): plain text, soft delete, edits kept in revision tables that
  only a trigger writes and only admins read (D169).
- `checkins` (D145): one per member per Dhaka week, immutable.
- `activity_events` (§9.1.6, D149): append-only evidence, written in the same transaction as the
  change through the `record_activity()` definer, or directly by SYSTEM.
- `risks`, `forecast_snapshots` (§9.11, D151): written by `monitoring.evaluate` as SYSTEM.
- `notification_preferences` (§7.8, D162): one row per user and §12 category.
"""

