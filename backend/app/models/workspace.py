class TaskEvidence(UUIDPrimaryKey, Timestamps, Base):
    __tablename__ = "task_evidence"

    project_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("projects.id", ondelete="CASCADE"), nullable=False
    )
    # No cascade: evidence is append-only, so a task with evidence can't be deleted (D173).
    task_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("tasks.id"), nullable=False)
    kind: Mapped[EvidenceKind] = mapped_column(
        _pg_enum(EvidenceKind, "evidence_kind"), nullable=False
    )
    file_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("files.id"))
    url: Mapped[str | None] = mapped_column(Text)
    note: Mapped[str | None] = mapped_column(Text)
    added_by: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), nullable=False)

    __table_args__ = (
        CheckConstraint(
            "(kind IN ('FILE', 'SCREENSHOT') AND file_id IS NOT NULL AND url IS NULL)"
            " OR (kind IN ('LINK', 'PR') AND url IS NOT NULL AND file_id IS NULL)",
            name="kind_shape",
        ),
        CheckConstraint(
            "url IS NULL OR (char_length(url) <= 2048 AND url ~ '^https://')", name="url_https"
        ),
        CheckConstraint(
            "kind <> 'PR' OR url ~ '^https://github\\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/pull/[0-9]+$'",
            name="pr_format",
        ),
        CheckConstraint("note IS NULL OR char_length(note) <= 500", name="note_len"),
        Index("ix_task_evidence_task", "task_id", "created_at"),
    )


